"""PEAK PCAN-View trace (``.trc``) import — see :mod:`ucando.pcantrc`.

The sample captures this was written against (a Maruti Suzuki Dzire recorded on
the OBD-2 port with PCAN-View v5.2) live under ``data/uploads/``, which is
gitignored, so every test here synthesises the format instead. Two of them use
``can.TRCWriter`` as an independent producer: it declares a *different* column
set from PCAN-View and writes ``$STARTTIME`` in UTC rather than local time, so
it exercises both dialects without needing a vendor file.
"""

import os
from array import array
from datetime import datetime, timezone

import can
import pytest

from ucando import logstore, pcantrc, txproject

# ---------------------------------------------------------------------------
# synthesising a .trc
# ---------------------------------------------------------------------------
#: PCAN-View's own header comment, the format's self-documenting ground truth.
_LOCAL_START = datetime(2026, 8, 19, 16, 18, 43, 567000)


def _ole(dt: datetime) -> float:
    """A naive datetime as an OLE Automation date (days since 1899-12-30)."""
    return (dt - datetime(1899, 12, 30)).total_seconds() / 86400.0


def _pcan_comment(dt: datetime) -> str:
    """``19-08-2026 16:18:43.567.0`` — note the second dot, which no stdlib parser eats."""
    return dt.strftime("%d-%m-%Y %H:%M:%S.%f")[:-3] + ".0"


def _v2_text(rows, *, start=_LOCAL_START, version="2.0",
             columns="N,O,T,I,d,l,D", comment=True):
    head = [f";$FILEVERSION={version}", f";$STARTTIME={_ole(start)!r}",
            f";$COLUMNS={columns}", ";"]
    if comment:
        head.append(f";   Start time: {_pcan_comment(start)}")
    head += [";   Generated by PCAN-View v5.2.0.926",
             ";---+-- ------+------ +- --+----- +- +- +- +- -- -- -- -- -- -- --"]
    return "\n".join(head + list(rows)) + "\n"


def _v2_row(n, off_ms, id_hex, data, direction="Rx", code="DT"):
    body = " ".join(f"{b:02X}" for b in data)
    return f"{n:>7} {off_ms:>13.3f} {code} {id_hex:>9} {direction} {len(data):<2} {body} "


def _write(tmp_path, name, text):
    p = tmp_path / name
    p.write_text(text, encoding="latin-1")
    return str(p)


def _basic_rows(base_off, n=6, step=10.0):
    """A handful of frames starting at *base_off* ms on the hardware timer."""
    return [_v2_row(i + 1, base_off + i * step, "03D0", bytes([i, 0, 0, 0, 0, 0, 0, 0]))
            for i in range(n)]


