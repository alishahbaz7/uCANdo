def test_python_can_is_the_oracle_for_ids_payloads_and_deltas(tmp_path):
    """Read a ``can.TRCWriter`` file both ways: only the anchor may differ.

    ``TRCWriter`` declares ``N,O,T,B,I,d,R,L,D`` where PCAN-View v5.2 declares
    ``N,O,T,I,d,l,D``, so this also proves the 2.x parser is driven by
    ``$COLUMNS`` rather than by fixed positions.
    """
    p = tmp_path / "w.trc"
    msgs = [can.Message(timestamp=1_700_000_000.0 + i * 0.01,
                        arbitration_id=0x100 + (i % 3),
                        data=bytes([i, i + 1, i + 2]), is_extended_id=False)
            for i in range(20)]
    msgs.append(can.Message(timestamp=1_700_000_000.5, arbitration_id=0x1ABCDEF,
                            data=b"\xde\xad\xbe\xef", is_extended_id=True))
    with can.TRCWriter(str(p)) as w:
        for m in msgs:
            w.on_message_received(m)

    ours = logstore.load(str(p), use_cache=False)
    ref = []
    with can.LogReader(str(p)) as r:
        for m in r:
            ref.append((m.arbitration_id, bytes(m.data), bool(m.is_extended_id), m.timestamp))

    assert len(ours) == len(ref) == len(msgs)
    assert [ours.ids[i] for i in range(len(ours))] == [r[0] for r in ref]
    assert [ours.payload(i) for i in range(len(ours))] == [r[1] for r in ref]
    assert [bool(ours.flags[i] & logstore.FLAG_EXT) for i in range(len(ours))] == \
           [r[2] for r in ref]
    for i in range(len(ref)):
        assert (ours.t[i] - ours.t[0]) == pytest.approx(ref[i][3] - ref[0][3], abs=1e-6)
    # TRCWriter states UTC in a tz-aware comment, so even the anchor agrees.
    assert ours.t[0] == pytest.approx(ref[0][3], abs=2e-3)


@pytest.mark.parametrize("version,rows,expect_tx", [
    # 1.0: no start time, no direction column, and a bus-info line to ignore.
    ("1.0", ["     1)      1000 0300  3  01 02 03",
             "     2)      1010 0301  1  AA",
             "     3)      1020 FFFFFFFF 4  00 00 00 00"], False),
    # 1.1: direction in field 3.
    ("1.1", ["     1)      1000 Rx 0300  3  01 02 03",
             "     2)      1010 Tx 0301  1  AA"], True),
    # 1.3: a bus column, then direction, then a reserved '-'.
    ("1.3", ["     1)      1000  1 Rx 0300 -  3  01 02 03",
             "     2)      1010  1 Tx 0301 -  1  AA"], True),
])
def test_legacy_layouts(tmp_path, version, rows, expect_tx):
    head = [f";$FILEVERSION={version}"]
    if version != "1.0":
        head += [f";$STARTTIME={_ole(_LOCAL_START)!r}",
                 f";   Start time: {_pcan_comment(_LOCAL_START)}"]
    text = "\n".join(head + [";"] + rows) + "\n"
    p = _write(tmp_path, f"v{version}.trc", text)
    store = logstore.load(p, use_cache=False)

    assert len(store) == 2                          # the FFFFFFFF bus line is not a frame
    assert store.payload(0) == b"\x01\x02\x03"
    assert store.t[1] - store.t[0] == pytest.approx(0.010, abs=1e-6)
    assert any(bool(store.flags[i] & logstore.FLAG_TX)
               for i in range(len(store))) is expect_tx
    if version == "1.0":
        # No $STARTTIME: timestamps are relative, and cross-file gaps cannot be
        # reconstructed from them. Say so rather than inventing an epoch.
        assert store.t[0] == pytest.approx(0.0, abs=1e-6)
        assert any("records no start time" in n for n in store.notes)


