def test_extended_ids(tmp_path):
    """PCAN-View writes 8 hex digits for a 29-bit id, 4 for an 11-bit one."""
    rows = [_v2_row(1, 0.0, "0CF00400", b"\x01\x02"),
            _v2_row(2, 10.0, "03D0", b"\x03\x04")]
