def test_cache_round_trips_the_notes_and_census(tmp_path):
    """The parse cache carries the reader's accounting, or it reappears empty."""
    rows = [_v2_row(1, 0.0, "03D0", b"\x01" * 8),
            "      2     232522.168 EV Hardware plug-out"]
    p = _write(tmp_path, "a.trc", _v2_text(rows))
    fresh = logstore.load(p, use_cache=False)
    logstore.load(p)                                          # populate
    cached = logstore._cache_read(p, os.stat(p))
    assert cached is not None
    assert cached.notes == fresh.notes
    assert cached.reader["census"] == fresh.reader["census"]
    assert cached.network_summary() == fresh.network_summary()
    assert cached.t[0] == fresh.t[0]


def test_a_trc_transmits_through_the_engine(vchannel):
    """End to end: the format is only supported if frames actually go out."""
    import tempfile
    from ucando.replay import TxEngine

    tmp = tempfile.mkdtemp()
    rows = [_v2_row(i + 1, 16620.0 + i * 2.0, "03D0", bytes([i, 1, 2, 3]))
            for i in range(25)]
    p = _write(__import__("pathlib").Path(tmp), "drive.trc", _v2_text(rows))

    sink = can.Bus(interface="virtual", channel=vchannel, receive_own_messages=False)
    tx = can.Bus(interface="virtual", channel=vchannel)
    try:
        eng = TxEngine()
        meta = eng.load(p)
        assert meta["frames"] == 25 and meta["network"] == "CAN 1"
        eng.play(tx.send)
        got = []
        deadline = 5.0
        import time
        t0 = time.time()
        while time.time() - t0 < deadline and len(got) < 25:
            m = sink.recv(0.1)
            if m is not None:
                got.append(m)
            elif eng.status()["state"] in ("done", "error"):
                break
        eng.stop()
        assert len(got) == 25
        assert [m.arbitration_id for m in got] == [0x3D0] * 25
        assert got[0].data == bytes([0, 1, 2, 3])
        assert eng.status()["health"]["errors"] == 0
    finally:
        sink.shutdown()
        tx.shutdown()
