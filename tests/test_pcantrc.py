def test_anchor_is_the_header_start_time_not_start_time_plus_offset(tmp_path):
    """The ``O`` column is a hardware timer, not an offset from ``$STARTTIME``.

    PCAN-View's timer keeps running across trace start/stop, so a file recorded
    16.6 s into a session opens at ``O = 16620``. ``$STARTTIME`` describes the
    *first frame*, so the anchor is ``$STARTTIME + (O - O_first)``. Adding the
    raw offset — what ``can.LogReader`` does — puts the capture 16.6 s late.
    """
    p = _write(tmp_path, "a.trc", _v2_text(_basic_rows(16620.386)))
    store = logstore.load(p, use_cache=False)

    want = _LOCAL_START.timestamp()
    assert store.t[0] == pytest.approx(want, abs=1e-3)
    # ... and specifically NOT the raw-offset reading.
    assert abs(store.t[0] - (want + 16.620386)) > 16.0
    # Deltas are untouched: this was always right, and replay pacing rides on it.
    assert store.t[-1] - store.t[0] == pytest.approx(0.050, abs=1e-6)


def test_startime_is_read_as_local_time(tmp_path):
    """PCAN-View writes ``$STARTTIME`` in local time; python-can reads it as UTC.

    Anywhere but UTC that is a whole-timezone error — 5:30 in India, where these
    captures come from.
    """
    p = _write(tmp_path, "a.trc", _v2_text(_basic_rows(0.0)))
    log = pcantrc.TrcLog(open(p, encoding="latin-1").read())
    assert log.anchor_source == "local-header"
    assert log.anchor == pytest.approx(_LOCAL_START.timestamp(), abs=1e-3)


def test_utc_startime_is_detected_from_a_tz_aware_comment(tmp_path):
    """``can.TRCWriter`` writes UTC. The file says which, so don't guess.

    Its ``Start time:`` comment is a tz-aware ISO string, and that settles the
    reading outright — the same ``$STARTTIME`` number would otherwise be an
    offset-hours error in the other direction.
    """
    utc_start = datetime(2026, 8, 19, 10, 48, 43, 567000, tzinfo=timezone.utc)
    naive = utc_start.replace(tzinfo=None)
    text = "\n".join([
        ";$FILEVERSION=2.1", f";$STARTTIME={_ole(naive)!r}",
        ";$COLUMNS=N,O,T,I,d,l,D", ";", f";   Start time: {utc_start}", ";",
    ] + _basic_rows(0.0)) + "\n"
    log = pcantrc.TrcLog(text)
    assert log.anchor_source == "utc-header"
    assert log.anchor == pytest.approx(utc_start.timestamp(), abs=1e-3)


def test_no_start_time_comment_falls_back_to_local(tmp_path):
    p = _write(tmp_path, "a.trc", _v2_text(_basic_rows(0.0), comment=False))
    log = pcantrc.TrcLog(open(p, encoding="latin-1").read())
    assert log.anchor_source == "local-assumed"
    assert any("no 'Start time' comment" in n for n in log.notes())


def test_auto_gap_survives_the_hardware_timer_offset(tmp_path):
    """The whole point of anchoring: cross-file pauses become real.

    Two captures of one session, recorded 120 s apart, whose hardware-timer
    offsets differ by an unrelated amount. Uncorrected, the second file looks
    like it starts *before* the first ends; corrected, ``auto`` recovers the
    real pause.
    """
    a_start = datetime(2026, 8, 19, 16, 0, 0)
    b_start = datetime(2026, 8, 19, 16, 2, 5)          # 125 s later, 5 s of A played
    a = _write(tmp_path, "a.trc", _v2_text(_basic_rows(90_000.0, n=6, step=1000.0),
                                           start=a_start))
    b = _write(tmp_path, "b.trc", _v2_text(_basic_rows(400.0, n=6, step=1000.0),
                                           start=b_start))
    plan = txproject.build([{"path": a}, {"path": b, "gap_before_ms": "auto"}],
                           use_cache=False)
    # A spans 16:00:00 -> 16:00:05; B opens at 16:02:05 => a 120 s pause.
    assert plan.segments[1].gap_s == pytest.approx(120.0, abs=1e-2)
    assert plan.segments[1].real_gap_s == pytest.approx(120.0, abs=1e-2)
    assert not [w for w in plan.warnings if "overlap" in w]


def test_pause_beyond_the_cap_is_reported_not_reproduced(tmp_path):
    """A 40-minute pause is real but nobody wants a bench run to sit through it.

    So it is not inserted — and not silently swallowed either, or ``auto`` would
    look as though it decided the two captures were contiguous.
    """
    a = _write(tmp_path, "a.trc", _v2_text(_basic_rows(0.0),
                                           start=datetime(2026, 8, 19, 16, 0, 0)))
    b = _write(tmp_path, "b.trc", _v2_text(_basic_rows(0.0),
                                           start=datetime(2026, 8, 19, 16, 40, 0)))
    plan = txproject.build([{"path": a}, {"path": b, "gap_before_ms": "auto"}],
                           use_cache=False)
    seg = plan.segments[1]
    assert seg.gap_s == 0.0                                  # unchanged behaviour
    assert seg.real_gap_s == pytest.approx(2399.95, abs=0.1)  # but measured
    assert any("real pause" in w and "40m00s" in w for w in plan.warnings)


